export const FEATURE_BY_ID = Object.fromEntries(FEATURES.map((f) => [f.id, f]));

/** Derive the headline verdict for a feature, optionally resolved for a country + language. */
export function verdictFor(feature, { country = null, langCodes = [] } = {}, ctx = {}) {
  if (feature.verdict && feature.verdict !== 'depends') return feature.verdict;
  const eu = resolveEu(feature, { country, langCodes }, ctx);
  const us = feature.us.status;
  if (eu.status === 'partial' || us === 'partial') return 'depends';
  if (us === 'yes' && eu.status === 'no') return 'us';
  if (us !== 'yes' && eu.status === 'yes') return 'eu';
  if (us === 'yes' && eu.status === 'yes') return 'same';
  if (us === 'no' && eu.status === 'no') return 'same';
  return 'mixed';
}

/**
 * Resolve the EU cell for a specific country/language.
 * ctx: { availability: {key: [codes]}, languageSupport: {key: [langCodes]} }
 */
export function resolveEu(feature, { country = null, langCodes = [] } = {}, ctx = {}) {
  const eu = feature.eu;
  if (eu.status !== 'partial') return { ...eu, resolved: false };
  if (eu.avail && country && ctx.availability?.[eu.avail]) {
    const ok = ctx.availability[eu.avail].includes(country);
    return { status: ok ? 'yes' : 'no', label: ok ? `Available in ${ctx.countryName || country}` : `Not in ${ctx.countryName || country}`, resolved: true };
  }
  if (eu.lang && langCodes.length && ctx.languageSupport?.[eu.lang]) {
    const supported = langCodes.filter((l) => ctx.languageSupport[eu.lang].includes(l));
    if (supported.length === langCodes.length) return { status: 'yes', label: 'Supported in your language', resolved: true };
    if (supported.length === 0) return { status: 'no', label: 'Not in your language (use English)', resolved: true };
    return { status: 'partial', label: 'Some of your languages', resolved: true };
  }
  return { ...eu, resolved: false };
}
